package com.stl.ngms.admin.model;

public class TotalFeedBackModel {
	private String feedBackName;
	private Integer excellent;
	private Integer good;
	private Integer average;
	private Integer poor;
	private Integer veryPoor;
	public String getFeedBackName() {
		return feedBackName;
	}
	public void setFeedBackName(String feedBackName) {
		this.feedBackName = feedBackName;
	}
	public Integer getExcellent() {
		return excellent;
	}
	public void setExcellent(Integer excellent) {
		this.excellent = excellent;
	}
	public Integer getGood() {
		return good;
	}
	public void setGood(Integer good) {
		this.good = good;
	}
	public Integer getAverage() {
		return average;
	}
	public void setAverage(Integer average) {
		this.average = average;
	}
	public Integer getPoor() {
		return poor;
	}
	public void setPoor(Integer poor) {
		this.poor = poor;
	}
	public Integer getVeryPoor() {
		return veryPoor;
	}
	public void setVeryPoor(Integer veryPoor) {
		this.veryPoor = veryPoor;
	}
	
	

}
