package com.stl.ngms.admin.model;

public class DriverWithVehicleDetails {
private String driverId;
private String driverName;
private String driverMobileNo;
private String vehicleNo;
private String vehicledesc;
private String protocolName;
private String protocolMobile;
public String getDriverId() {
	return driverId;
}
public void setDriverId(String driverId) {
	this.driverId = driverId;
}
public String getDriverName() {
	return driverName;
}
public void setDriverName(String driverName) {
	this.driverName = driverName;
}
public String getDriverMobileNo() {
	return driverMobileNo;
}
public void setDriverMobileNo(String driverMobileNo) {
	this.driverMobileNo = driverMobileNo;
}
public String getVehicleNo() {
	return vehicleNo;
}
public void setVehicleNo(String vehicleNo) {
	this.vehicleNo = vehicleNo;
}
public String getVehicledesc() {
	return vehicledesc;
}
public void setVehicledesc(String vehicledesc) {
	this.vehicledesc = vehicledesc;
}
public String getProtocolName() {
	return protocolName;
}
public void setProtocolName(String protocolName) {
	this.protocolName = protocolName;
}
public String getProtocolMobile() {
	return protocolMobile;
}
public void setProtocolMobile(String protocolMobile) {
	this.protocolMobile = protocolMobile;
}


}
